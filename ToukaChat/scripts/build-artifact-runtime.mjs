// 產生 artifact 沙箱 runtime bundle（選項 A，ADR-0114）。
//
// 用既有的 esbuild 把 src/lib/artifacts/runtime-entry.ts（含 React 19，無 UMD）打包成單一
// 瀏覽器 IIFE，輸出成 src/generated/artifactRuntime.ts 的字串常數 ARTIFACT_RUNTIME，供
// ReactRenderer lazy import 後 inline 進預覽 iframe 的 <script>。
//
// 此產物 gitignore（避免把縮小化字串 commit 進版控 / 版本漂移）。dev 會明示生成；
// Daily CI 與受管 build 在來源就緒後明示呼叫 gen:artifact-runtime，不依賴 npm lifecycle。
// npm ci --ignore-scripts 不會生成此檔；乾淨來源測試前必須生成並核對產物非空。
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outDir = resolve(root, "src/generated");

// 流程圖沙箱框的 mermaid（ADR-0294）：原樣複製 mermaid 自己的瀏覽器版，輸出成 MERMAID_RUNTIME 字串常數，
// 只在沙箱框裡執行（src/lib/artifacts/mermaidSandbox.ts）。不需要 esbuild，所以在下面的跳過之前產生。
const mermaidJs = readFileSync(createRequire(import.meta.url).resolve("mermaid/dist/mermaid.min.js"), "utf8");
const mermaidFile = resolve(outDir, "mermaidRuntime.ts");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  mermaidFile,
  "// AUTO-GENERATED by scripts/build-artifact-runtime.mjs — DO NOT EDIT (gitignored).\n" +
    "// 流程圖沙箱框的 mermaid 瀏覽器版。見 ADR-0294。\n" +
    `export const MERMAID_RUNTIME = ${JSON.stringify(mermaidJs)};\n`,
  "utf8",
);
// eslint-disable-next-line no-console
console.log(`[artifact-runtime] wrote ${mermaidFile} (${mermaidJs.length} bytes)`);

// esbuild 為 devDependency：生產安裝（npm ci --omit=dev）時可能不存在，保持既有跳過行為。
// 需要此產物的 build／CI 呼叫端另核對輸出非空，不能將跳過當成已生成。
let esbuild;
try {
  esbuild = (await import("esbuild")).default;
} catch {
  // eslint-disable-next-line no-console
  console.log("[artifact-runtime] esbuild 不可用（可能是 --omit=dev 安裝）；跳過生成。");
  process.exit(0);
}

const entry = resolve(root, "src/lib/artifacts/runtime-entry.ts");
const outFile = resolve(outDir, "artifactRuntime.ts");

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2018",
  minify: true,
  write: false,
  // 生產版 React（去開發警告、縮小體積）。
  define: { "process.env.NODE_ENV": '"production"' },
});

const js = result.outputFiles[0].text;
mkdirSync(outDir, { recursive: true });
const banner =
  "// AUTO-GENERATED by scripts/build-artifact-runtime.mjs — DO NOT EDIT (gitignored).\n" +
  "// Artifact 沙箱 runtime（含 React 19）。見 ADR-0114。\n";
writeFileSync(
  outFile,
  `${banner}export const ARTIFACT_RUNTIME = ${JSON.stringify(js)};\n`,
  "utf8",
);
// eslint-disable-next-line no-console
console.log(`[artifact-runtime] wrote ${outFile} (${js.length} bytes)`);
