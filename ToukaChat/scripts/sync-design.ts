import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, PRIMITIVES, AGENT_TOKENS, SEMANTIC_TOKENS } from '../src/lib/design-system/tokens';

/**
 * Design Sync Script (Bridge)
 * 將 TypeScript 的 Tokens 同步至 CSS 檔案中。
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const GLOBALS_CSS_PATH = join(__dirname, '../src/app/globals.css');

function syncDesign() {
  console.log('🚀 Starting Design Sync...');

  let cssContent = readFileSync(GLOBALS_CSS_PATH, 'utf8');

  // 1. 生成 @theme inline 區塊
  const themeBlockEntries = [
    `  /* --- Generated by sync-design.ts --- */`,
    `  --radius-lg: ${SEMANTIC_TOKENS.radius};`,
    `  --radius-sm: calc(var(--radius-lg) - 4px);`,
    `  --radius-md: calc(var(--radius-lg) - 2px);`,
    `  --font-sans: ${SEMANTIC_TOKENS.font.sans};`,
    `  --font-display: ${SEMANTIC_TOKENS.font.display};`,
    `  --font-mono: ${SEMANTIC_TOKENS.font.mono};`,
    ``,
    `  /* Agent Tokens */`,
    ...Object.entries(AGENT_TOKENS).flatMap(([name, token]) => [
        `  --color-agent-${name.toLowerCase()}: ${token.primary};`,
        `  --color-agent-${name.toLowerCase()}-accent: ${token.accent};`,
    ]),
    ``,
    `  /* Brand Tokens */`,
    ...Object.entries(SEMANTIC_TOKENS.brand).flatMap(([name, color]) => [
        `  --color-brand-${name}: ${color};`,
    ]),
    ``,
    `  /* Status Tokens */`,
    ...Object.entries(SEMANTIC_TOKENS.status).flatMap(([name, color]) => [
        `  --color-status-${name}: ${color};`,
    ]),
    ``,
    `  /* Core Semantic Mappings (Ensuring @apply works for standard utilities) */`,
    `  --color-background: var(--background);`,
    `  --color-foreground: var(--foreground);`,
    `  --color-primary: var(--primary);`,
    `  --color-primary-button: var(--primary-button);`,
    `  --color-primary-foreground: var(--primary-foreground);`,
    `  --color-input: var(--input);`,
    `  --color-border: var(--border);`,
    `  --color-card: var(--card);`,
    `  --color-card-foreground: var(--card-foreground);`,
    `  --color-popover: var(--popover);`,
    `  --color-popover-foreground: var(--popover-foreground);`,
    `  --color-secondary: var(--secondary);`,
    `  --color-secondary-foreground: var(--secondary-foreground);`,
    `  --color-destructive: var(--destructive);`,
    `  --color-destructive-foreground: var(--destructive-foreground);`,
    `  --color-sidebar: var(--sidebar);`,
    `  --color-sidebar-foreground: var(--sidebar-foreground);`,
    `  --color-ring: var(--ring);`,
    `  --color-muted: var(--muted);`,
    `  --color-muted-foreground: var(--muted-foreground);`,
    `  --color-accent: var(--accent);`,
    `  --color-accent-foreground: var(--accent-foreground);`,
  ];

  // 2. 生成 :root 基礎變數 (以 Touka 經典主題作為預設)
  const defaultTheme = THEMES.touka;
  const rootEntries = [
    `  /* --- Generated Default Theme --- */`,
    `  --background: ${defaultTheme.bg};`,
    `  --foreground: ${PRIMITIVES.touka[900]};`,
    `  --primary: ${defaultTheme.primary};`,
    `  --primary-button: ${defaultTheme.primaryButton};`,
    `  --primary-foreground: ${PRIMITIVES.white};`,
    `  --card: ${defaultTheme.surface};`,
    `  --card-foreground: ${PRIMITIVES.white};`,
    `  --sidebar: ${defaultTheme.surface};`,
    `  --border: ${defaultTheme.border};`,
    `  --input: ${defaultTheme.inputBorder};`,
  ];

  // 使用 Regex 替換 CSS 中的標記區塊
  // 假設我們在 CSS 中有 /* @tokens-start */ ... /* @tokens-end */
  const replaceSection = (content: string, tag: string, newEntries: string[]) => {
    const startTag = `/* @${tag}-start */`;
    const endTag = `/* @${tag}-end */`;
    
    // 使用更寬鬆的匹配（允許空格差異）
    const regex = new RegExp(`\\/\\*\\s*@${tag}-start\\s*\\*\\/[\\s\\S]*?\\/\\*\\s*@${tag}-end\\s*\\*\\/`, 'g');
    
    if (!regex.test(content)) {
        console.warn(`⚠️ Warning: Section @${tag} not found in globals.css`);
        return content;
    }
    
    console.log(`✅ Syncing section: @${tag}`);
    return content.replace(regex, `${startTag}\n${newEntries.join('\n')}\n  ${endTag}`);
  };

  cssContent = replaceSection(cssContent, 'theme-block', themeBlockEntries);
  cssContent = replaceSection(cssContent, 'root-vars', rootEntries);

  writeFileSync(GLOBALS_CSS_PATH, cssContent);
  console.log('✅ Design Sync Complete: globals.css updated.');
}

syncDesign();
