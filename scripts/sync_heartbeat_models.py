"""Project the pure Heartbeat model source without importing service bootstrap."""

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ToukaHeartbeat" / "models.py"
OUTPUT = ROOT / "ToukaProxy" / "src" / "models" / "heartbeat_schedule.py"
HEADER = "# Generated by scripts/sync_heartbeat_models.py; edit ToukaHeartbeat/models.py only.\n"


def projection_bytes() -> bytes:
    """Validate pure imports and produce deterministic projection bytes."""
    source = SOURCE.read_text(encoding="utf-8")
    tree = ast.parse(source)
    allowed = {"typing", "pydantic", "json", "hashlib"}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level or node.module not in allowed):
            raise ValueError("heartbeat_model_requires_pure_imports")
        if isinstance(node, ast.Import) and any(alias.name not in allowed for alias in node.names):
            raise ValueError("heartbeat_model_requires_pure_imports")
    return (HEADER + source).encode("utf-8")


def sync() -> None:
    """Write the generated model projection from its sole source."""
    OUTPUT.write_bytes(projection_bytes())


def check() -> None:
    """Fail on projection drift without rewriting the candidate."""
    if OUTPUT.read_bytes() != projection_bytes():
        raise ValueError("heartbeat_model_projection_drift")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check() if args.check else sync()
