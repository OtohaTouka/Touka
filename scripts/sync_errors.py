"""Synchronizes backend error definitions to frontend TypeScript codes."""

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ERRORS_JSON = PROJECT_ROOT / "ToukaProxy" / "config" / "errors.json.example"
TS_OUTPUT = PROJECT_ROOT / "ToukaChat" / "src" / "lib" / "error_codes.ts"
HEARTBEAT_OUTPUT = PROJECT_ROOT / "ToukaHeartbeat" / "error_codes.py"


def sync() -> None:
    """Project the shipped error registry without reading private configuration."""
    if not ERRORS_JSON.exists():
        print(f"Error: {ERRORS_JSON} not found.")  # noqa: T201
        sys.exit(1)

    with Path(ERRORS_JSON).open(encoding="utf-8") as f:
        errors = json.load(f)

    # Validate unique IDs
    ids = {}
    duplicates = {}
    for key, val in errors.items():
        err_id = val.get("id")
        if err_id in ids:
            duplicates[err_id] = duplicates.get(err_id, [ids[err_id]])
            duplicates[err_id].append(key)
        else:
            ids[err_id] = key

    if duplicates:
        print("Error: Detected duplicate error code IDs in errors.json!")  # noqa: T201
        for err_id, keys in duplicates.items():
            print(f"  ID {err_id} is used by: {', '.join(keys)}")  # noqa: T201
        sys.exit(1)

    ts_content = [
        "// [SSOT] This file is automatically generated by scripts/sync_errors.py",
        "// DO NOT EDIT MANUALLY.",
        "",
        "export const ERRORS = {",
    ]

    for key, val in errors.items():
        ts_content.append(f"  {key}: {{")
        ts_content.append(f"    id: {val['id']},")
        ts_content.append(f"    status: {val['status']},")
        ts_content.append(f'    msg: "{val["msg"]}",')
        ts_content.append(f'    i18n: "{val.get("i18n", "")}"')
        ts_content.append("  },")

    ts_content.append("} as const;")
    ts_content.append("")
    ts_content.append("export type ErrorCode = keyof typeof ERRORS;")

    TS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with Path(TS_OUTPUT).open("w", encoding="utf-8") as f:
        f.write("\n".join(ts_content))

    heartbeat_errors = {key: value for key, value in errors.items() if key.startswith("HEARTBEAT_")}
    heartbeat_lines = [
        '"""Generated by scripts/sync_errors.py from errors.json.example; do not edit."""',
        "",
        "ERRORS = {",
    ]
    for key, value in heartbeat_errors.items():
        heartbeat_lines.append(f'    "{key}": {{')
        for field, item in value.items():
            heartbeat_lines.append(f'        "{field}": {json.dumps(item, ensure_ascii=False)},')
        heartbeat_lines.append("    },")
    heartbeat_lines.extend(["}", ""])
    heartbeat_content = "\n".join(heartbeat_lines)
    HEARTBEAT_OUTPUT.write_text(heartbeat_content, encoding="utf-8")

    print(f"Synced {len(errors)} error codes to {TS_OUTPUT}")  # noqa: T201


if __name__ == "__main__":
    sync()
